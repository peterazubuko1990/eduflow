                                    your school academic status by monitoring subject syllabus status in percentage.
                                    Every class section teach subjects. Subjects are based on syllabus which contains
                                    lesson / chapter / unit and lesson / chapter / unit contains topics further topic
                                    may contain sub topic also.</p>
                                    <p>Lesson plan is basically what a teacher will teach in a class &ndash; section for
                                        a particular day period. Through lesson plan teachers can divide subject
                                        syllabus lesson topic in different period over the span of academic session.
                                        Lesson plan also very useful for students to check what they will study in
                                        upcoming periods or what they have learned in past periods so for best practice
                                        teachers should create their lesson plan at least for one week in advance.</p>
                                    <p>In lesson plan you can also upload class lecture recording and attach teaching
                                        material.</p><strong>Lesson Plan Module Workflow</strong>: First we will add
                                    <strong>all lesson</strong> under a <strong>subject</strong> then we will add
                                    <strong>all topics</strong> under a <strong>lesson</strong> then we will add
                                    <strong>lesson plan</strong> for selected period from <strong>teachers time
                                        table</strong> then we can mark<strong> subject lesson topic</strong> as
                                    <strong>complete</strong> after it finally we can check<strong> lesson plan
