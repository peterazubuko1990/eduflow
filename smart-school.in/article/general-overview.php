                                    <p><strong>Admin Panel consist 26 modules listed below -</strong><br/><br/>1.
                                        <strong>Front Office</strong> - For all reception / front office related
                                        activities like enquiries, calls, visitors, postal receive/dispatch.<br/>2.
                                        <strong>Student Information</strong> - For all the information related to
                                        student like student profile, student admission, student history.<br/>3.
                                        <strong>Fees Collection</strong> - For all the details related to student fees
                                        collection, fees master creation, fees dues, fees reports<br/>4.
                                        <strong>Income</strong> - For all the income other than fees collection can be
                                        manage here like add income, search income, income head<br/>5.
                                        <strong>Expenses</strong> - For all the expenses related to school can be manage
                                        here like add expenses, search expenses, expense head<br/>6.
                                        <strong>Attendance</strong> - For managing student attendance and attendance
                                        report<br/>7. <strong>Examinations</strong> - For managing all the exams
                                        conducted by school like create exam, schedule exam, exam marks entry, marks
                                        grade<br/>8. <strong>Online Examinations</strong> - For managing online exams
                                        conducted by school<br/>9. <strong>Lesson Plan</strong> - For managing subject
                                        status and lesson plan<br/>10. <strong>Academics</strong> - For managing all the
                                        parameters / master data required to run school like classes, sections,
                                        subjects, assign teachers, class timetable, promote student to upper class<br/>11.
                                        <strong>Human Resource</strong> - For all the information related to staff
                                        members can be manage here like staff search, profile, attendance, payroll,
                                        leaves<br/>12. <strong>Communicate</strong> - It works like a notice board
                                        basically a messaging system for communication to students, parents and teachers<br/>13.
                                        <strong>Download Center</strong> - For managing downloadable documents like
                                        assignments, study material, syllabus and other documents need to distribute
                                        students and teachers<br/>14. <strong>Homework</strong> - Teachers can give
                                        homework here and further evaluate them<br/>15. <strong>Library</strong> - All
                                        the books in your library can be manage here<br/>16. <strong>Inventory</strong>
                                        - Manage all the assets of your school with stocks and store under inventory
                                        module<br/>17. <strong>Transport</strong> - For managing transportation service
                                        like routes and their fares<br/>18. <strong>Hostel</strong> - For managing
                                        hostels, hostel rooms and their fares<br/>19. <strong>Certificate</strong> -
                                        Design and generate student certificate and ID card here<br/>20. <strong>Front
                                            CMS</strong> - Manage front public site of Eduflow here by creating
                                        pages, menus, events, gallery, news<br/>21. <strong>Alumni</strong> - For
                                        managing all pass out students or alumni records and events<br/>22. <strong>Reports</strong>
                                        - All the various reports related to different modules can be found here<br/>23.
                                        <strong>System Settings</strong> - Configure Eduflow here for different
                                        settings like school, sessions, SMS, Payment, backup / restore, languages<br/>24.
                                        <strong>Calendar &amp; To Do List</strong> - Track and manage all daily/monthly
                                        activities and create your task in to do list<br/>25. <strong>Chat</strong> -
                                        Chat for two way messaging staff and students<br/>26. <strong>One Click
                                            Updater</strong> - To install new in system</p>
