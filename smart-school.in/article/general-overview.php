                                    <br/><br/><span style="font-size: 14pt;"><strong>To understand how Eduflow works first we need to configure and setup it for our school. In this whole documentation we will consider our sample school which is Mount Carmel School.<br/><br/>Steps to setup your school -<br/></strong></span><span
                                            style="font-size: 14pt;"><span style="font-size: 12pt;"><br/>1. In the Admin panel go to <strong>System Setting &gt; General Setting.</strong><br/><br/><img
                                            src="../assets/article-media/01SS.png" alt="" width="1920"
                                            height="955"/><br/></span></span><strong><br/></strong>2. Update your
                                    <strong>School Name</strong>, <strong>School Code</strong> (School Code is your
                                    school affiliation / accreditation no), <strong>Address</strong>,
                                    <strong>Phone</strong>, <strong>Email</strong> (for remaining settings please check
                                    System Settings section) now click on <strong>Save</strong> button to update record.<br/><br/>3.
                                    For updating your school print logo go to <strong>System Setting &gt; General
                                        Setting</strong> in lower left side click on Edit Print Logo button (it is
                                    recommended for logo to use .png image with transparent or white background and
                                    around 200px x 200px in size). Now drag and drop or select your logo file. By
                                    clicking on <strong>Edit</strong> <strong>Admin Logo</strong> and
                                    <strong>Edit</strong> <strong>Admin Small Logo</strong> you can set logo for admin
                                    panel. <strong>Edit App Logo</strong> to set logo for mobile app.<br/><br/><img
                                            src="../assets/article-media/logos.png" alt="" width="1913"
                                            height="939"/><br/><br/>4. For automated SMS messaging add any one of
                                    available SMS Gateway with the required details from <strong>System Setting &gt; SMS
                                        Setting</strong>.<br/><br/><img src="../assets/article-media/sms.png" alt=""
                                                                        width="1920" height="938"/><br/><br/>5. To
                                    enabling online payment in Parent Panel and Student Panel update your payment
                                    gateway account details for this, go to <strong>System Setting &gt; Payment
                                        Methods</strong> select your appropriate payment gateway and add you payment
                                    gateway account details then click on save button and enable it from right side box.<br/><br/><img
                                            src="../assets/article-media/Payment%20Methods.png" alt="" width="1920"
                                            height="939"/><br/><br/>6. For updating Header image and Footer content of
                                    Fees Receipt and Payslip&nbsp; go to <strong>System Setting &gt; Print Header
                                        Footer</strong>, then drag and drop or select your Header Image and enter Footer
                                    Content and then click save it. You can update Header image and Footer content for&nbsp;
                                    <strong>Fees Receipt, Payslip, and Online Admission Receipt </strong>and <strong>Online
                                        Exam</strong> by switching tab from top right corner of the page.<br/><br/><img
                                            src="../assets/article-media/04SS.png" alt="" width="1920"
                                            height="955"/><br/><br/>7. At this point we have completed basic setup of
                                    our school. Now we will add our academics in Eduflow like Classes, Sections,
                                    Subjects, Teachers.<br/><br/>8. For adding classes go to <strong>Academics &gt;
                                        Classes</strong>, before adding classes first add Sections from <strong>Academics
                                        &gt; Sections</strong>. Select Sections comes under a Class when you adding a
                                    Class. Classes can be add from left side Add Class form and added classes can be see
                                    right side<strong> Class List</strong>. Add all classes running in your school here.<br/><br/><img
                                            src="../assets/article-media/ss001.png" alt="" width="1920"
                                            height="955"/><br/><br/>9. For adding sections go to&nbsp;<strong>Academics
                                        &gt; Sections</strong>, Sections can be add from left side&nbsp;<strong>Add
                                        Section</strong>&nbsp;form and added section can be see right side&nbsp;<strong>Section
                                        List</strong>. Add all section name used in your school here e.g. Class 1 has 3
                                    sections A, B, C and Class 2 has only A, B sections then we will add 3 sections A,
                                    B, C here. After adding sections, select section comes in a Class when you adding
                                    Classes.<br/><br/><img src="../assets/article-media/section.png" alt="" width="1920"
                                                           height="940"/><br/><br/>10. For adding subjects go to
                                    <strong>Academics &gt; Subjects</strong>, Subjects can be add from left
                                    side&nbsp;<strong>Add Subject</strong>&nbsp;form and added subjects can be see right
                                    side&nbsp;<strong>Subject List</strong>. Add all subjects including theory and
                                    practical in your school here. Subjects can be assign through Subject Groups to
                                    their classes in next step.<br/><br/><img src="../assets/article-media/subjects.png"
                                                                              alt="" width="1914"
                                                                              height="941"/><br/><br/><br/>11. For
                                    assigning subjects to their classes go to <strong>Academics &gt; Subject
                                        Group</strong>&nbsp;enter Subject Group then select Class and Section then
                                    select all subjects you want to include in this class and section as group now click
                                    on&nbsp;<strong>Save</strong>.<br/><br/><img src="../assets/article-media/05SS.png"
                                                                                 alt="" width="1920" height="955"/><br/><br/>12.
                                    For adding Teachers go to <strong>Human Resource &gt; Staff Directory</strong>,
                                    Teachers can be add from top right corner <strong>Add Staff</strong> button. At this
                                    page you can add any staff by selecting its role. If we are creating teacher then we
                                    should select role (Teacher) and designation.<br/><br/><img
                                            src="../assets/article-media/ss03.png" alt="" width="1920"
                                            height="955"/><br/><br/>13. Great! you have completed your <strong>Smart
                                        School</strong> setup. To understand each module in detail, go to its concerning
                                    article.<br/><strong><br/></strong></article>
