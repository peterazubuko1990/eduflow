                                <article class="article-body">Before start using Eduflow consider a general
                                    scenario of typical school of class 1 to 12th, each classes have sections like
                                    Section A, Section B. There will various subjects for different classes like some
                                    subjects are theory and some are practical. Exams are created using these subjects
                                    and classes. Students enter in classes by new admission or promoted by their
                                    previous class after successful passing of previous class. During course of student
                                    we will charge fees to students and collecting them at monthly or one time basis. We
                                    like to record attendance of our students. Our school may be providing transport
                                    facility to student. Our school have library for students have to maintain books
                                    inventory. Our school have hostels and providing hostel facility to our students.
                                    Obviously our school has teachers to teach and manage students. We like to
                                    communicate our teachers, students and parents. We like to record all the expenses
                                    done in our school like miscellaneous bills, salary payments etc. After everything
                                    we like to analyze various reports based on our school.<br/><br/>If you are using
                                    Eduflow for a training Centre then may be you like to admit students in two
                                    classes, for this you should use multi class feature where you can admit a single
                                    student in two classes simultaneously.<br/><br/>Apart from above we also like to
                                    provide access to our Eduflow to other users like Teachers, Accountants,
                                    Librarians, Students and their Parent. For these Eduflow have 8 inbuilt user's
                                    roles-&nbsp;<strong>SuperAdmin</strong>,&nbsp;<strong>Admin</strong>,&nbsp;<strong>Teacher</strong>,&nbsp;<strong>Accountant</strong>,&nbsp;<strong>Librarian</strong>,
                                    <strong>Receptionist</strong>,&nbsp;<strong>Student&nbsp;</strong>and&nbsp;<strong>Parent</strong>.
                                    Virtually you can create unlimited number of user roles for staff members.<br/><br/><strong><span
                                            style="font-size: 14pt;">Admin Panel :- </span></strong><span
                                            style="font-size: 12pt;">Login to Admin Panel through URL</span><span
