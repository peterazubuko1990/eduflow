                                    <div dir="ltr" data-identifyelement="323">To set values for Student Admission No.
                                        Auto Generation here it is recommend to set prefix any alphabet character like
                                        <strong>SA</strong> and if you select Admission No Digit as 4 so you must set
                                        Admission Start From value of <strong>4 digit</strong> like
                                        <strong>1000</strong> or <strong>1001</strong> otherwise it will show error.
                                        Also make sure auto generated admission no. will not conflict in future with any
                                        existing admission no. (with manually entered Admission No.
                                        value).<br/><br/><img
                                                src="../assets/article-media/03%20enabled%20student%20admission%20no%20auto%20generations.png"
                                                alt="" width="1366" height="674"/><br/>
                                        <p><br/>If you keep this mode <strong>enabled</strong>, than you do not need to
                                            manually generate the admission number, it will generate automatically.&nbsp;To
                                            <strong>Generate</strong> <strong>Admission</strong> <strong>No</strong>
                                            <strong>Automatically</strong> you have to fill the
                                            <strong>Admission</strong> <strong>No</strong>. <strong>Prefix,</strong>
                                            <strong>Admission</strong> <strong>No.</strong> <strong>Digit </strong>and
                                            <strong>Admission</strong> <strong>Start</strong> <strong>From </strong>and
                                            click on save button, your student admission no. auto generation will be
                                            active.<br/><br/><strong>Staff ID Auto Generation<br/><br/></strong>To set
                                            Staff ID Number automatically go to <strong>System Settings &gt; General
                                                Setting &gt; ID Auto Generation</strong> and set Auto Staff ID&nbsp;from
                                            Disabled to Enable.</p>
                                        <div dir="ltr" data-identifyelement="323">To set values for <strong>Staff ID No.
                                            Auto Generation</strong> here it is recommend to set prefix any alphabet
                                            character like <strong>SI</strong> and if you select Staff ID No Digit as 4
