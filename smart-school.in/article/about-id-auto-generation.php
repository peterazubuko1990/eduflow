                                    <div dir="ltr" data-identifyelement="319"><p>ID auto generation refers to the
                                        process of automatically creating a unique identifier for a piece of data or
                                        record. This can be done through various methods, such as using a database's
                                        built-in auto-incrementing feature, or by generating a random alphanumeric
                                        string. The purpose of an auto-generated ID is to ensure that each record in a
                                        database has a unique identifier, which can be used to easily retrieve and
                                        manage the data.<br/><br/><strong>Student Admission No. Auto Generation</strong>
                                    </p>To set Student Admission Number automatically go to <strong><strong>System
                                        Settings &gt; General Setting &gt; ID</strong>&nbsp;Auto Generation</strong> and
                                        change <span data-identifyelement="320">Admission No</span>&nbsp;from Disabled
                                        to Enable.
                                    </div>
